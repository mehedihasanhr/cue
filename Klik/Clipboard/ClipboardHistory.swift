import os
import AppKit
import Carbon.HIToolbox
import Observation

/// Everything copied on this Mac, newest first: text, links, colors, images and
/// files. Watches the pasteboard by polling its change count (there is no
/// notification), records which app copied it, and keeps the list bounded.
///
/// Every pasteboard type of a copy is kept (plain text *and* RTF *and* HTML, PNG
/// *and* TIFF…), so pasting from the history gives the target app exactly what the
/// original copy would have — formatted text stays formatted. Storage is SQLite in
/// the app container (Application Support/Klik/Clipboard/history.sqlite): metadata in
/// `items`, the raw pasteboard data in `contents`, a small thumbnail per image.
@Observable
final class ClipboardHistory {
    private(set) var items: [ClipboardItem] = []
    var limit = 200 {
        didSet { trim() }
    }
    /// Bumped when a thumbnail arrives, so cards showing a placeholder refresh.
    private(set) var thumbnailVersion = 0

    @ObservationIgnored private var thumbnails = LRUCache<UUID, NSImage>(capacity: 300)
    /// Rich flavours already parsed for the previews (nil: the entry has none).
    @ObservationIgnored private var richTexts: [UUID: NSAttributedString?] = [:]
    @ObservationIgnored private var loadingThumbnails: Set<UUID> = []
    @ObservationIgnored private var icons: [String: NSImage] = [:]
    @ObservationIgnored private var timer: Timer?
    @ObservationIgnored private var lastChangeCount: Int
    @ObservationIgnored private let storage = DispatchQueue(label: "com.stackrover.klik.clipboard", qos: .utility)
    @ObservationIgnored private let database: SQLiteDatabase?
    private let folderURL: URL

    /// Pasteboard types that ask not to be recorded (credential managers, transient data).
    private static let concealedTypes: [NSPasteboard.PasteboardType] = [
        NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"),
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
        NSPasteboard.PasteboardType("com.agilebits.onepassword"),
    ]
    /// Text kept in memory for the cards and search; the full text is in the blobs.
    private static let previewLength = 20_000
    /// A single pasteboard flavour bigger than this is not kept.
    private static let maxBlobSize = 64 << 20
    private static let pollInterval: TimeInterval = 0.5

    init() {
        let support = FileManager.default.urls(for: .applicationSupportDirectory, in: .userDomainMask).first
            ?? FileManager.default.temporaryDirectory
        folderURL = support.appendingPathComponent("Klik/Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: folderURL, withIntermediateDirectories: true)
        lastChangeCount = NSPasteboard.general.changeCount
        do {
            let database = try SQLiteDatabase(url: folderURL.appendingPathComponent("history.sqlite"))
            try database.execute(Self.schema)
            // Added after the first release; harmless when the column exists.
            try? database.execute("ALTER TABLE items ADD COLUMN name TEXT")
            try? database.execute("ALTER TABLE items ADD COLUMN group_id TEXT")
            self.database = database
        } catch {
            Log.app.error("Clipboard history: cannot open database: \(String(describing: error), privacy: .public)")
            database = nil
        }
        migrateJSONIfNeeded()
        loadItems()
        // PNGs written for dragging images out are only needed for that drag.
        let folder = folderURL
        storage.async {
            let files = (try? FileManager.default.contentsOfDirectory(at: folder, includingPropertiesForKeys: nil)) ?? []
            for file in files where file.lastPathComponent.hasPrefix("drag-") { try? FileManager.default.removeItem(at: file) }
        }
    }

    private static let schema = """
        CREATE TABLE IF NOT EXISTS items (
            id TEXT PRIMARY KEY,
            kind TEXT NOT NULL,
            text TEXT NOT NULL,
            pixel_width INTEGER NOT NULL DEFAULT 0,
            pixel_height INTEGER NOT NULL DEFAULT 0,
            source_bundle TEXT,
            source_name TEXT,
            created REAL NOT NULL,
            pinned INTEGER NOT NULL DEFAULT 0,
            thumbnail BLOB,
            name TEXT
        );
        CREATE INDEX IF NOT EXISTS items_created ON items(created DESC);
        CREATE TABLE IF NOT EXISTS contents (
            item_id TEXT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
            item_index INTEGER NOT NULL,
            type TEXT NOT NULL,
            data BLOB NOT NULL
        );
        CREATE INDEX IF NOT EXISTS contents_item ON contents(item_id);
        """

    // MARK: - Watching

    var isWatching: Bool { timer != nil }

    func startWatching() {
        guard timer == nil else { return }
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: Self.pollInterval, repeats: true) { [weak self] _ in
            MainActor.assumeIsolated { self?.poll() }
        }
        timer.tolerance = 0.2
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
        Log.app.info("Clipboard history: watching")
    }

    func stopWatching() {
        timer?.invalidate()
        timer = nil
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let count = pasteboard.changeCount
        guard count != lastChangeCount else { return }
        lastChangeCount = count
        record(pasteboard)
    }

    /// Reads whatever is on the pasteboard now and stores it (unless it is marked as
    /// concealed, is one of Klik's own copies, or repeats the newest item).
    private func record(_ pasteboard: NSPasteboard) {
        let types = pasteboard.types ?? []
        guard !types.contains(where: Self.concealedTypes.contains), !types.contains(Clipboard.ownMarker) else { return }
        guard let pasteboardItems = pasteboard.pasteboardItems, !pasteboardItems.isEmpty else { return }
        let source = NSWorkspace.shared.frontmostApplication

        // Every flavour of every item, so a paste can reproduce the copy exactly.
        var contents: [Content] = []
        for (index, pasteboardItem) in pasteboardItems.enumerated() {
            for type in pasteboardItem.types where type != Clipboard.ownMarker {
                guard let data = pasteboardItem.data(forType: type), data.count <= Self.maxBlobSize else { continue }
                contents.append(Content(index: index, type: type.rawValue, data: data))
            }
        }
        guard !contents.isEmpty else { return }

        var item: ClipboardItem
        var thumbnail: Data?
        if let urls = pasteboard.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map { $0.path(percentEncoded: false) }
            item = ClipboardItem(kind: .files, text: paths.joined(separator: "\n"))
        } else if let string = pasteboard.string(forType: .string), !string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            let (kind, text) = ClipboardItem.classify(String(string.prefix(Self.previewLength)))
            item = ClipboardItem(kind: kind, text: text)
        } else if let data = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff),
                  let imageSource = CGImageSourceCreateWithData(data as CFData, nil),
                  let properties = CGImageSourceCopyPropertiesAtIndex(imageSource, 0, nil) as? [CFString: Any],
                  let width = properties[kCGImagePropertyPixelWidth] as? Int,
                  let height = properties[kCGImagePropertyPixelHeight] as? Int {
            item = ClipboardItem(kind: .image, text: "Image", pixelWidth: width, pixelHeight: height)
            if let image = ImageEncoding.thumbnail(from: imageSource) {
                thumbnails[item.id] = image
                thumbnail = image.cgImage(forProposedRect: nil, context: nil, hints: nil).flatMap(ImageEncoding.png)
            }
        } else {
            return // nothing Klik knows how to show
        }
        item.sourceBundleID = source?.bundleIdentifier
        item.sourceName = source?.localizedName

        if let newest = items.first, newest.kind == item.kind, newest.text == item.text, item.kind != .image {
            // Same thing copied again: refresh its time, and its flavours — the same
            // words may now come with formatting (or without).
            items[0].createdAt = item.createdAt
            update(items[0])
            replaceContents(of: items[0], with: contents)
            return
        }
        items.insert(item, at: 0)
        insert(item, thumbnail: thumbnail, contents: contents)
        trim()
    }

    private struct Content: Sendable {
        let index: Int
        let type: String
        let data: Data
    }

    /// The entry's text with its formatting, when it was copied with RTF or HTML:
    /// what the previews show as the original. Parsed once per entry.
    func richText(for item: ClipboardItem) -> NSAttributedString? {
        guard item.kind == .text else { return nil }
        if let cached = richTexts[item.id] { return cached }
        let contents = (try? database?.query(
            "SELECT type, data FROM contents WHERE item_id = ? AND item_index = 0 AND type IN (?, ?)",
            [.text(item.id.uuidString), .text(NSPasteboard.PasteboardType.rtf.rawValue), .text(NSPasteboard.PasteboardType.html.rawValue)]
        ) { row in (type: row.text(0) ?? "", data: row.blob(1) ?? Data()) }) ?? []
        var rich: NSAttributedString?
        if let rtf = contents.first(where: { $0.type == NSPasteboard.PasteboardType.rtf.rawValue }) {
            rich = NSAttributedString(rtf: rtf.data, documentAttributes: nil)
        } else if let html = contents.first(where: { $0.type == NSPasteboard.PasteboardType.html.rawValue }), html.data.count < 400_000 {
            rich = NSAttributedString(html: html.data, options: [.characterEncoding: String.Encoding.utf8.rawValue], documentAttributes: nil)
                .map(Self.systemFonts)
        }
        if let text = rich, text.string.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty { rich = nil }
        richTexts[item.id] = .some(rich)
        return rich
    }

    // MARK: - Actions

    /// Puts the item back on the pasteboard with every flavour it was copied with
    /// (without recording it again) and, unless told otherwise, moves it to the top
    /// like a fresh copy.
    func copy(_ item: ClipboardItem, promote: Bool = true) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        let contents = (try? database?.query(
            "SELECT item_index, type, data FROM contents WHERE item_id = ? ORDER BY item_index, rowid",
            [.text(item.id.uuidString)]
        ) { row in Content(index: Int(row.integer(0)), type: row.text(1) ?? "", data: row.blob(2) ?? Data()) }) ?? []

        if contents.isEmpty {
            // A failed read: the preview, or the thumbnail for a picture, is all there is.
            if item.kind == .image, let thumbnail = thumbnails[item.id], let tiff = thumbnail.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
                if let png = NSBitmapImageRep(data: tiff)?.representation(using: .png, properties: [:]) {
                    pasteboard.setData(png, forType: .png)
                }
            } else {
                pasteboard.setString(item.text, forType: .string)
            }
        } else {
            var pasteboardItems: [NSPasteboardItem] = []
            for content in contents {
                while pasteboardItems.count <= content.index { pasteboardItems.append(NSPasteboardItem()) }
                pasteboardItems[content.index].setData(content.data, forType: NSPasteboard.PasteboardType(content.type))
            }
            // A picture stored as PNG alone pastes nowhere in apps that ask for TIFF;
            // plain text likewise stands in for a flavour only its own app understands.
            if let first = pasteboardItems.first {
                let types = Set(contents.filter { $0.index == 0 }.map(\.type))
                if types.contains(NSPasteboard.PasteboardType.png.rawValue), !types.contains(NSPasteboard.PasteboardType.tiff.rawValue),
                   let png = contents.first(where: { $0.index == 0 && $0.type == NSPasteboard.PasteboardType.png.rawValue })?.data,
                   let tiff = NSBitmapImageRep(data: png)?.tiffRepresentation {
                    first.setData(tiff, forType: .tiff)
                }
                if !types.contains(NSPasteboard.PasteboardType.string.rawValue), !item.text.isEmpty, item.kind != .image {
                    first.setString(item.text, forType: .string)
                }
                first.setData(Data(), forType: Clipboard.ownMarker)
            }
            pasteboard.writeObjects(pasteboardItems)
        }
        lastChangeCount = pasteboard.changeCount
        if promote { self.promote(item) }
    }

    /// Moves the item to the top like a fresh copy — for a copy that could not
    /// promote at once, because its card would have jumped under the pointer.
    func promote(_ item: ClipboardItem) {
        guard let index = items.firstIndex(of: item), index > 0 else { return }
        var moved = items.remove(at: index)
        moved.createdAt = .now
        items.insert(moved, at: 0)
        update(moved)
    }

    // MARK: - Paste stack

    /// Where the next ⌘⇧V paste comes from: the position in `items` (0 = newest).
    /// Starts over after a pause, or when something new is copied.
    @ObservationIgnored private var stackPosition = 0
    @ObservationIgnored private var stackTouched = Date.distantPast
    @ObservationIgnored private var stackCount = 0

    /// Pastes the next entry in the history — newest first, then the one before it,
    /// and so on — without reordering the history. Returns what was pasted and its
    /// position, or nil when there is nothing or pasting is impossible.
    @discardableResult
    func pasteNext() -> (item: ClipboardItem, position: Int, of: Int)? {
        let unpinnedOrder = items // pins stay in place: the stack is the history as shown
        guard !unpinnedOrder.isEmpty else { return nil }
        let fresh = Date().timeIntervalSince(stackTouched) > 90 || stackCount != unpinnedOrder.count
        if fresh { stackPosition = 0 }
        stackCount = unpinnedOrder.count
        stackTouched = Date()
        let item = unpinnedOrder[stackPosition % unpinnedOrder.count]
        copy(item, promote: false)
        stackCount = items.count // unchanged by the copy, but keep it honest
        guard pressPaste() else { return nil }
        let position = stackPosition
        stackPosition = (stackPosition + 1) % unpinnedOrder.count
        return (item, position + 1, unpinnedOrder.count)
    }

    /// Pastes several entries as one text, newest last, joined by newlines.
    @discardableResult
    func paste(joined entries: [ClipboardItem]) -> Bool {
        let text = entries.reversed().map(\.text).joined(separator: "\n")
        copy(text: text)
        return pressPaste()
    }

    /// Puts plain text on the pasteboard without recording it (a transform, an
    /// answer): the history keeps what was copied, not what Klik derived from it.
    func copy(text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        pasteboard.setData(Data(), forType: Clipboard.ownMarker)
        lastChangeCount = pasteboard.changeCount
    }

    /// A pasteboard item with every flavour the entry was copied with, for dragging it
    /// into other apps. Images also get a PNG file (in the clipboard folder) so Finder
    /// and file-only targets accept the drop; file entries carry their original URLs.
    func dragPayload(for item: ClipboardItem) -> DragPayload? {
        let contents = (try? database?.query(
            "SELECT item_index, type, data FROM contents WHERE item_id = ? ORDER BY item_index, rowid",
            [.text(item.id.uuidString)]
        ) { row in Content(index: Int(row.integer(0)), type: row.text(1) ?? "", data: row.blob(2) ?? Data()) }) ?? []
        let pasteboardItem = NSPasteboardItem()
        for content in contents where content.index == 0 {
            pasteboardItem.setData(content.data, forType: NSPasteboard.PasteboardType(content.type))
        }
        var preview: NSImage?
        switch item.kind {
        case .files:
            guard let first = item.filePaths.first else { return nil }
            let url = URL(fileURLWithPath: first)
            return DragPayload(writer: url as NSURL, preview: NSWorkspace.shared.icon(forFile: url.path))
        case .image:
            let url = folderURL.appendingPathComponent("drag-\(item.id.uuidString).png")
            if FileManager.default.fileExists(atPath: url.path) {
                pasteboardItem.setString(url.absoluteString, forType: .fileURL) // written by an earlier drag
            } else if let png = contents.first(where: { $0.type == NSPasteboard.PasteboardType.png.rawValue })?.data
                ?? contents.first.flatMap({ CGImageSourceCreateWithData($0.data as CFData, nil) }).flatMap({ CGImageSourceCreateImageAtIndex($0, 0, nil) }).flatMap(ImageEncoding.png) {
                try? png.write(to: url, options: .atomic)
                pasteboardItem.setString(url.absoluteString, forType: .fileURL)
            }
            preview = thumbnails[item.id]
        case .text, .link, .color:
            if contents.isEmpty { pasteboardItem.setString(item.text, forType: .string) }
            preview = Self.textPreview(item.title)
        }
        return DragPayload(writer: pasteboardItem, preview: preview ?? Self.textPreview(item.title))
    }

    /// A small card image for dragging text.
    private static func textPreview(_ text: String) -> NSImage {
        let size = CGSize(width: 160, height: 60)
        return NSImage(size: size, flipped: false) { rect in
            NSColor(white: 0.12, alpha: 0.95).setFill()
            NSBezierPath(roundedRect: rect, xRadius: 10, yRadius: 10).fill()
            let attributes: [NSAttributedString.Key: Any] = [.font: NSFont.systemFont(ofSize: 11), .foregroundColor: NSColor.white]
            (text as NSString).draw(in: rect.insetBy(dx: 10, dy: 10), withAttributes: attributes)
            return true
        }
    }

    /// A Klik text view that should receive pastes instead of the front app — the
    /// quick-task form while it is open. Set by the app delegate.
    var openEditor: () -> NSTextView? = { nil }

    /// Whether `paste` has somewhere to go: an open Klik editor, or the front app
    /// through a typed ⌘V (needs Accessibility).
    var canPaste: Bool { openEditor() != nil || PermissionManager.hasAccessibilityAccess }

    /// Copies the item and pastes it. Returns false (after copying) when there is
    /// nowhere to paste, so the caller can say "press ⌘V".
    @discardableResult
    func paste(_ item: ClipboardItem) -> Bool {
        copy(item)
        return pressPaste()
    }

    /// Pastes whatever is on the pasteboard: into Klik's own open editor when there
    /// is one, otherwise by pressing ⌘V in the front app.
    /// `field`: where the cursor was before Klik took activation for one of its
    /// panels; the app gets activation back and the field its focus, and ⌘V is sent
    /// once that has settled so the keystroke lands there.
    @discardableResult
    func pressPaste(returningTo field: FrontField? = nil) -> Bool {
        if let editor = openEditor() {
            editor.window?.makeKeyAndOrderFront(nil)
            editor.window?.makeFirstResponder(editor)
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { editor.paste(nil) }
            return true
        }
        guard PermissionManager.hasAccessibilityAccess else {
            Log.app.notice("Paste: no Accessibility access")
            return false
        }
        Log.app.info("Paste: to \(field?.app?.localizedName ?? "the front app", privacy: .public), Klik active \(NSApp.isActive)")
        if let field, field.isOtherApp {
            field.restore { Self.postCommandV() }
        } else {
            // A beat for the pasteboard to settle before the key press lands.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.15, execute: Self.postCommandV)
        }
        return true
    }

    /// Hands activation from Klik to `app` (the cooperative way macOS 14 wants).
    static func activate(_ app: NSRunningApplication) {
        NSApp.yieldActivation(to: app)
        app.activate(from: .current, options: [])
    }

    /// Gives the field (if given) its focus back and presses ⌘V once it has it, for
    /// anything Klik puts on the pasteboard to land where the cursor was.
    static func pressCommandV(returningTo field: FrontField?, then done: @escaping @MainActor () -> Void = {}) {
        if let field, field.isOtherApp {
            field.restore { postCommandV(); done() }
        } else {
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) { postCommandV(); done() }
        }
    }

    /// Runs `action` once `app` is the frontmost application (polled, with a beat for
    /// its key window to take focus back), or after a second regardless.
    static func whenFrontmost(_ app: NSRunningApplication, attempts: Int = 20, then action: @escaping @MainActor () -> Void) {
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.05) {
            if NSWorkspace.shared.frontmostApplication == app || attempts <= 1 {
                DispatchQueue.main.asyncAfter(deadline: .now() + 0.12, execute: action)
            } else {
                whenFrontmost(app, attempts: attempts - 1, then: action)
            }
        }
    }

    private static func postCommandV() {
        let source = CGEventSource(stateID: .combinedSessionState)
        for down in [true, false] {
            guard let event = CGEvent(keyboardEventSource: source, virtualKey: CGKeyCode(kVK_ANSI_V), keyDown: down) else { continue }
            event.flags = .maskCommand
            event.post(tap: .cghidEventTap)
        }
    }

    func togglePin(_ item: ClipboardItem) {
        guard let index = items.firstIndex(of: item) else { return }
        items[index].pinned.toggle()
        update(items[index])
    }

    /// Puts the entry in a group (nil: out of any).
    func setGroup(_ item: ClipboardItem, _ groupID: UUID?) {
        guard let index = items.firstIndex(where: { $0.id == item.id }), items[index].groupID != groupID else { return }
        items[index].groupID = groupID
        update(items[index])
    }

    /// A deleted group's entries are ungrouped.
    func removeGroup(_ groupID: UUID) {
        for index in items.indices where items[index].groupID == groupID {
            items[index].groupID = nil
            update(items[index])
        }
    }

    /// Gives the entry a label (empty clears it).
    func rename(_ item: ClipboardItem, to name: String) {
        guard let index = items.firstIndex(of: item) else { return }
        let cleaned = name.trimmingCharacters(in: .whitespacesAndNewlines)
        items[index].name = cleaned.isEmpty ? nil : cleaned
        update(items[index])
    }

    func delete(_ item: ClipboardItem) {
        items.removeAll { $0.id == item.id }
        thumbnails[item.id] = nil
        remove([item])
    }

    /// Removes everything except pinned items.
    func clear() {
        let removed = items.filter { !$0.pinned && $0.groupID == nil }
        items.removeAll { !$0.pinned && $0.groupID == nil }
        for item in removed { thumbnails[item.id] = nil }
        remove(removed)
    }

    // MARK: - Images & icons

    /// The cached thumbnail, or nil while it loads from the database (cards showing a
    /// placeholder refresh through `thumbnailVersion`).
    func thumbnail(for item: ClipboardItem) -> NSImage? {
        _ = thumbnailVersion
        if let cached = thumbnails[item.id] { return cached }
        guard item.kind == .image, let database, !loadingThumbnails.contains(item.id) else { return nil }
        loadingThumbnails.insert(item.id)
        let id = item.id
        storage.async { [weak self] in
            let rows = try? database.query("SELECT thumbnail FROM items WHERE id = ?", [.text(id.uuidString)]) { $0.blob(0) }
            let image = rows?.first.flatMap { $0 }.flatMap { NSImage(data: $0) }
            Task { @MainActor in
                guard let self else { return }
                self.loadingThumbnails.remove(id)
                guard let image else { return }
                self.thumbnails[id] = image
                self.thumbnailVersion += 1
            }
        }
        return nil
    }

    /// The stored image data of an image entry (PNG preferred, else TIFF), for previews.
    func imageData(for item: ClipboardItem) -> Data? {
        guard item.kind == .image, let database else { return nil }
        let rows = (try? database.query(
            "SELECT type, data FROM contents WHERE item_id = ? AND item_index = 0", [.text(item.id.uuidString)]
        ) { ($0.text(0) ?? "", $0.blob(1)) }) ?? []
        return rows.first { $0.0 == NSPasteboard.PasteboardType.png.rawValue }?.1
            ?? rows.first { $0.0 == NSPasteboard.PasteboardType.tiff.rawValue }?.1
    }

    /// The icon of the app the item was copied from.
    func sourceIcon(for item: ClipboardItem) -> NSImage? {
        guard let bundleID = item.sourceBundleID else { return nil }
        if let cached = icons[bundleID] { return cached }
        guard let url = NSWorkspace.shared.urlForApplication(withBundleIdentifier: bundleID) else { return nil }
        let icon = NSWorkspace.shared.icon(forFile: url.path)
        icons[bundleID] = icon
        return icon
    }

    // MARK: - Persistence

    private typealias Value = SQLiteDatabase.Value

    private func loadItems() {
        guard let database else { return }
        do {
            items = try database.query(
                "SELECT id, kind, text, pixel_width, pixel_height, source_bundle, source_name, created, pinned, name, group_id FROM items ORDER BY created DESC"
            ) { row in
                var item = ClipboardItem(
                    id: UUID(uuidString: row.text(0) ?? "") ?? UUID(),
                    kind: ClipboardItem.Kind(rawValue: row.text(1) ?? "") ?? .text,
                    text: row.text(2) ?? "",
                    pixelWidth: Int(row.integer(3)), pixelHeight: Int(row.integer(4)),
                    sourceBundleID: row.text(5), sourceName: row.text(6),
                    createdAt: Date(timeIntervalSince1970: row.double(7))
                )
                item.pinned = row.bool(8)
                item.name = row.text(9)
                item.groupID = row.text(10).flatMap(UUID.init(uuidString:))
                return item
            }
        } catch {
            Log.app.error("Clipboard history: cannot load: \(String(describing: error), privacy: .public)")
        }
    }

    private func insert(_ item: ClipboardItem, thumbnail: Data?, contents: [Content]) {
        guard let database else { return }
        storage.async {
            do {
                try database.transaction {
                    try database.run(
                        "INSERT OR REPLACE INTO items (id, kind, text, pixel_width, pixel_height, source_bundle, source_name, created, pinned, thumbnail) VALUES (?,?,?,?,?,?,?,?,?,?)",
                        [.text(item.id.uuidString), .text(item.kind.rawValue), .text(item.text),
                         .integer(Int64(item.pixelWidth)), .integer(Int64(item.pixelHeight)),
                         item.sourceBundleID.map(Value.text) ?? .null, item.sourceName.map(Value.text) ?? .null,
                         .real(item.createdAt.timeIntervalSince1970), .integer(item.pinned ? 1 : 0),
                         thumbnail.map(Value.blob) ?? .null]
                    )
                    for content in contents {
                        try database.run(
                            "INSERT INTO contents (item_id, item_index, type, data) VALUES (?,?,?,?)",
                            [.text(item.id.uuidString), .integer(Int64(content.index)), .text(content.type), .blob(content.data)]
                        )
                    }
                }
            } catch {
                Log.app.error("Clipboard history: cannot save: \(String(describing: error), privacy: .public)")
            }
        }
    }

    /// HTML without a font of its own comes out in Times; the system font reads
    /// better and is what the page most likely used. Weights and slants are kept.
    private static func systemFonts(_ text: NSAttributedString) -> NSAttributedString {
        let copy = NSMutableAttributedString(attributedString: text)
        copy.enumerateAttribute(.font, in: NSRange(location: 0, length: copy.length)) { value, range, _ in
            guard let font = value as? NSFont, font.familyName == "Times" || font.familyName == "Times New Roman" else { return }
            let traits = NSFontManager.shared.traits(of: font)
            var replacement = NSFont.systemFont(ofSize: font.pointSize, weight: traits.contains(.boldFontMask) ? .bold : .regular)
            if traits.contains(.italicFontMask) { replacement = NSFontManager.shared.convert(replacement, toHaveTrait: .italicFontMask) }
            copy.addAttribute(.font, value: replacement, range: range)
        }
        return copy
    }

    /// The flavours of an entry copied again, in place of the old ones.
    private func replaceContents(of item: ClipboardItem, with contents: [Content]) {
        guard let database else { return }
        richTexts[item.id] = nil
        storage.async {
            try? database.transaction {
                try database.run("DELETE FROM contents WHERE item_id = ?", [.text(item.id.uuidString)])
                for content in contents {
                    try database.run(
                        "INSERT INTO contents (item_id, item_index, type, data) VALUES (?,?,?,?)",
                        [.text(item.id.uuidString), .integer(Int64(content.index)), .text(content.type), .blob(content.data)]
                    )
                }
            }
        }
    }

    private func update(_ item: ClipboardItem) {
        guard let database else { return }
        storage.async {
            try? database.run(
                "UPDATE items SET created = ?, pinned = ?, name = ?, group_id = ? WHERE id = ?",
                [.real(item.createdAt.timeIntervalSince1970), .integer(item.pinned ? 1 : 0), item.name.map(Value.text) ?? .null,
                 item.groupID.map { Value.text($0.uuidString) } ?? .null, .text(item.id.uuidString)]
            )
        }
    }

    private func remove(_ removed: [ClipboardItem]) {
        guard let database, !removed.isEmpty else { return }
        let ids = removed.map(\.id.uuidString)
        storage.async {
            try? database.transaction {
                for id in ids { try database.run("DELETE FROM items WHERE id = ?", [.text(id)]) }
            }
        }
    }

    /// Pinned items survive; the oldest unpinned ones go.
    private func trim() {
        guard items.count > limit else { return }
        let keepUnpinned = max(0, limit - items.filter(\.pinned).count)
        var unpinnedSeen = 0
        var removed: [ClipboardItem] = []
        items = items.filter { item in
            if item.pinned { return true }
            unpinnedSeen += 1
            if unpinnedSeen <= keepUnpinned { return true }
            removed.append(item)
            return false
        }
        for item in removed { thumbnails[item.id] = nil }
        remove(removed)
    }

    /// The first release kept a JSON index and PNG files; they move into the database
    /// once, with the plain text / file URLs / PNG as their only flavour.
    private func migrateJSONIfNeeded() {
        let indexURL = folderURL.appendingPathComponent("index.json")
        guard database != nil, let data = try? Data(contentsOf: indexURL),
              let decoded = try? JSONDecoder().decode([ClipboardItem].self, from: data)
        else { return }
        for item in decoded {
            var contents: [Content] = []
            var thumbnail: Data?
            switch item.kind {
            case .text, .link, .color:
                contents.append(Content(index: 0, type: NSPasteboard.PasteboardType.string.rawValue, data: Data(item.text.utf8)))
            case .files:
                for (index, path) in item.filePaths.enumerated() {
                    contents.append(Content(index: index, type: NSPasteboard.PasteboardType.fileURL.rawValue,
                                            data: Data(URL(fileURLWithPath: path).absoluteString.utf8)))
                }
            case .image:
                let url = folderURL.appendingPathComponent(item.fileName)
                guard let png = try? Data(contentsOf: url) else { continue }
                contents.append(Content(index: 0, type: NSPasteboard.PasteboardType.png.rawValue, data: png))
                thumbnail = ImageEncoding.thumbnail(at: url)?.cgImage(forProposedRect: nil, context: nil, hints: nil).flatMap(ImageEncoding.png)
                try? FileManager.default.removeItem(at: url)
            }
            insert(item, thumbnail: thumbnail, contents: contents)
        }
        try? FileManager.default.removeItem(at: indexURL)
        Log.app.info("Clipboard history: migrated \(decoded.count) item(s) to SQLite")
    }
