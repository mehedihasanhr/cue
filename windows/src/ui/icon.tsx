export type IconName = keyof typeof ICONS;

/** `size` is the icon's box; `weight` the stroke on its 24-point grid (1.5 is regular). */
export function Icon({ name, size = 14, weight = 1.5, className }: { name: IconName; size?: number; weight?: number; className?: string }) {
  return <HugeiconsIcon icon={ICONS[name]} size={size} strokeWidth={weight} color="currentColor" className={className} aria-hidden />;
}

/** The Mac's `Font.Weight` as a stroke: medium 1.7, semibold 1.9, bold 2.1. */
export const STROKE = { regular: 1.5, medium: 1.7, semibold: 1.9, bold: 2.1 } as const;
